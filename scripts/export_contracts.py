"""Deterministic schema/type generation; no network or configuration secrets are read."""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'apps/api'))
from app.main import ScheduleResponse, QueryRequest, app
from app.modules.config.schema import DisplayConfig, PreviewRequest, PublishDraft, Rollback, SaveDraft
from app.modules.forms.schema import FormConfig, default_form
from app.modules.approvals.schema import LeaveConfig, default_leave
from app.modules.intent.construction_ai import Proposal, GenerateConstruction


def ts(schema):
    if '$ref' in schema:
        return schema['$ref'].split('/')[-1]
    if 'const' in schema:
        return json.dumps(schema['const'], ensure_ascii=False)
    if 'enum' in schema:
        return ' | '.join(json.dumps(value, ensure_ascii=False) for value in schema['enum'])
    if 'anyOf' in schema:
        return '(' + ' | '.join(ts(item) for item in schema['anyOf']) + ')'
    kind = schema.get('type')
    if kind == 'array':
        return f'Array<{ts(schema["items"])}>'
    if kind == 'object':
        # These are serialized DTOs; model_dump includes default fields unless explicitly excluded.
        return '{ ' + '; '.join(json.dumps(key) + ': ' + ts(value)
                                for key, value in schema.get('properties', {}).items()) + ' }'
    return {'string': 'string', 'integer': 'number', 'number': 'number',
            'boolean': 'boolean', 'null': 'null'}.get(kind, 'unknown')


def outputs():
    schemas = {}
    for model in (ScheduleResponse, QueryRequest, DisplayConfig, PreviewRequest, PublishDraft, Rollback, SaveDraft):
        schema = model.model_json_schema(mode='serialization')
        schemas.update(schema.pop('$defs', {}))
        schemas[model.__name__] = schema
    types = '// Generated by scripts/export_contracts.py. Do not edit. Serialized DTOs.\n'
    types += '\n'.join(f'export type {name} = {ts(schema)};' for name, schema in sorted(schemas.items())) + '\n'
    form_schema = FormConfig.model_json_schema(mode='serialization')
    form_schema.update({'$schema': 'https://json-schema.org/draft/2020-12/schema', '$id': 'urn:campus:application-types:v1:form-config'})
    leave_schema = LeaveConfig.model_json_schema(mode='serialization')
    leave_schema.update({'$schema': 'https://json-schema.org/draft/2020-12/schema', '$id': 'urn:campus:application-types:v1:leave-config'})
    construction = {}
    for name, model in [('construction-proposal', Proposal), ('construction-request', GenerateConstruction)]:
        schema = model.model_json_schema()
        schema.update({'$schema': 'https://json-schema.org/draft/2020-12/schema', '$id': 'urn:campus:application-types:v1:' + name})
        construction[name] = json.dumps(schema, ensure_ascii=False, indent=2, sort_keys=True) + '\n'
    return {
        ROOT / 'packages/contracts/openapi.json': json.dumps(app.openapi(), ensure_ascii=False, indent=2, sort_keys=True) + '\n',
        ROOT / 'packages/contracts/config.schema.json': json.dumps(DisplayConfig.model_json_schema(), ensure_ascii=False, indent=2, sort_keys=True) + '\n',
        ROOT / 'apps/web/src/generated/contracts.ts': types,
        ROOT / 'packages/contracts/application-types/v1/form-config.schema.json': json.dumps(form_schema, ensure_ascii=False, indent=2, sort_keys=True) + '\n',
        ROOT / 'packages/contracts/application-types/v1/examples/form-config.json': json.dumps(default_form().model_dump(), ensure_ascii=False, indent=2, sort_keys=True) + '\n',
        ROOT / 'packages/contracts/application-types/v1/leave-config.schema.json': json.dumps(leave_schema, ensure_ascii=False, indent=2, sort_keys=True) + '\n',
        ROOT / 'packages/contracts/application-types/v1/examples/leave-config.json': json.dumps(default_leave().model_dump(), ensure_ascii=False, indent=2, sort_keys=True) + '\n',
        ROOT / 'packages/contracts/application-types/v1/construction-proposal.schema.json': construction['construction-proposal'],
        ROOT / 'packages/contracts/application-types/v1/construction-request.schema.json': construction['construction-request'],
    }


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    options = parser.parse_args()
    stale = []
    for path, content in outputs().items():
        if options.check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8')
    if stale:
        print('Stale contracts:', ', '.join(stale))
        raise SystemExit(1)
    print('Contracts OK')
